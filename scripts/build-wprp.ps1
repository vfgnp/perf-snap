<#
.SYNOPSIS
  Builds src\PerfSnap\Resources\PerfSnap.wprp from the built-in WPR profiles, with bounded memory buffers.

.DESCRIPTION
  The built-in profiles size their memory buffers from installed RAM (about 1.3 GB on a 7.7 GB PC when combined).
  This script exports CPU, DiskIO, Minifilter, DesktopComposition, FileIO and Registry with
  "wpr -exportprofile", merges their providers into two PerfSnap profiles and replaces the buffer counts
  with placeholders that PerfSnap fills in at run time:
    {SYSTEM_BUFFERS}  number of 1 MB buffers for the kernel (system) collector
    {EVENT_BUFFERS}   number of 1 MB buffers for the user-mode (event) collector

  Profiles produced (each in Memory and File logging mode):
    PerfSnap_InputLatency = CPU + DiskIO + Minifilter + DesktopComposition
    PerfSnap_Detailed     = the above + FileIO + Registry

  Run again when Windows updates its built-in profiles. Does not need administrator rights.
#>
param(
    [string]$Out = (Join-Path $PSScriptRoot '..\src\PerfSnap\Resources\PerfSnap.wprp')
)
$ErrorActionPreference = 'Stop'
$work = Join-Path ([IO.Path]::GetTempPath()) ("perfsnap-wprp-" + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $work | Out-Null

$sets = [ordered]@{
    'PerfSnap_InputLatency' = @('CPU', 'DiskIO', 'Minifilter', 'DesktopComposition')
    'PerfSnap_Detailed'     = @('CPU', 'DiskIO', 'Minifilter', 'DesktopComposition', 'FileIO', 'Registry')
}
$all = $sets.Values | ForEach-Object { $_ } | Select-Object -Unique
$exported = @{}
foreach ($p in $all) {
    $file = Join-Path $work "$p.wprp"
    & (Join-Path $env:WINDIR 'System32\wpr.exe') -exportprofile $p $file | Out-Null
    if (-not (Test-Path $file)) { throw "wpr -exportprofile $p failed" }
    $exported[$p] = [xml](Get-Content $file -Raw)
}

# Merge one event provider definition into another (same provider GUID): OR the keywords, keep the higher level,
# keep stacks if any source wants them.
function Merge-Provider([Xml.XmlElement]$into, [Xml.XmlElement]$from) {
    foreach ($attr in 'Stack', 'NonPagedMemory') {
        if ($from.GetAttribute($attr) -eq 'true') { $into.SetAttribute($attr, 'true') }
    }
    if ($from.HasAttribute('Level')) {
        $lv = [int]$from.GetAttribute('Level')
        if (-not $into.HasAttribute('Level') -or [int]$into.GetAttribute('Level') -lt $lv) { $into.SetAttribute('Level', "$lv") }
    }
    foreach ($section in 'Keywords', 'CaptureStateOnSave') {
        $src = $from.SelectSingleNode($section)
        if ($null -eq $src) { continue }
        $dst = $into.SelectSingleNode($section)
        if ($null -eq $dst) { [void]$into.AppendChild($into.OwnerDocument.ImportNode($src, $true)); continue }
        $mask = [uint64]0
        foreach ($k in @($dst.SelectNodes('Keyword')) + @($src.SelectNodes('Keyword'))) { $mask = $mask -bor [Convert]::ToUInt64($k.Value, 16) }
        $dst.RemoveAll()
        foreach ($a in $src.Attributes) { $dst.SetAttribute($a.Name, $a.Value) }
        $kw = $dst.OwnerDocument.CreateElement('Keyword'); $kw.SetAttribute('Value', ('0x{0:X16}' -f $mask)); [void]$dst.AppendChild($kw)
    }
}

$doc = New-Object Xml.XmlDocument
$root = $doc.CreateElement('WindowsPerformanceRecorder'); $root.SetAttribute('Version', '1.0'); $root.SetAttribute('Author', 'PerfSnap')
$root.SetAttribute('Comments', 'Generated by scripts/build-wprp.ps1 from the built-in WPR profiles. Buffers are bounded; see docs/03-detailed-design.md.')
[void]$doc.AppendChild($root)
$profilesEl = $doc.CreateElement('Profiles'); [void]$root.AppendChild($profilesEl)

$sys = $doc.CreateElement('SystemCollector'); $sys.SetAttribute('Id', 'PerfSnap_System'); $sys.SetAttribute('Name', 'PerfSnap System Collector')
$sys.InnerXml = '<BufferSize Value="1024" /><Buffers Value="{SYSTEM_BUFFERS}" />'
$evt = $doc.CreateElement('EventCollector'); $evt.SetAttribute('Id', 'PerfSnap_Event'); $evt.SetAttribute('Name', 'PerfSnap Event Collector')
$evt.InnerXml = '<BufferSize Value="1024" /><Buffers Value="{EVENT_BUFFERS}" />'
[void]$profilesEl.AppendChild($sys); [void]$profilesEl.AppendChild($evt)

$sysProviders = New-Object 'System.Collections.Generic.List[Xml.XmlElement]'
$evtProviders = New-Object 'System.Collections.Generic.List[Xml.XmlElement]'
$profileEls = New-Object 'System.Collections.Generic.List[Xml.XmlElement]'
foreach ($name in $sets.Keys) {
    $keywords = New-Object 'System.Collections.Generic.SortedSet[string]'
    $stacks = New-Object 'System.Collections.Generic.SortedSet[string]'
    $providers = [ordered]@{}
    foreach ($p in $sets[$name]) {
        $x = $exported[$p].WindowsPerformanceRecorder.Profiles
        foreach ($k in @($x.SystemProvider.Keywords.Keyword)) { if ($k) { [void]$keywords.Add($k.Value) } }
        foreach ($s in @($x.SystemProvider.Stacks.Stack)) { if ($s) { [void]$stacks.Add($s.Value) } }
        foreach ($ep in @($x.EventProvider)) {
            $id = $ep.GetAttribute('Id')
            if ($providers.Contains($id)) { Merge-Provider $providers[$id] $ep }
            else { $providers[$id] = $doc.ImportNode($ep, $true) }
        }
    }

    $spId = "${name}_SystemProvider"
    $sp = $doc.CreateElement('SystemProvider'); $sp.SetAttribute('Id', $spId)
    $kwEl = $doc.CreateElement('Keywords'); foreach ($k in $keywords) { $e = $doc.CreateElement('Keyword'); $e.SetAttribute('Value', $k); [void]$kwEl.AppendChild($e) }
    $stEl = $doc.CreateElement('Stacks'); foreach ($s in $stacks) { $e = $doc.CreateElement('Stack'); $e.SetAttribute('Value', $s); [void]$stEl.AppendChild($e) }
    [void]$sp.AppendChild($kwEl); [void]$sp.AppendChild($stEl); $sysProviders.Add($sp)

    $epIds = @()
    foreach ($id in $providers.Keys) {
        $el = $providers[$id]
        $newId = "${name}_$id"
        $el.SetAttribute('Id', $newId)
        $evtProviders.Add($el)
        $epIds += $newId
    }

    foreach ($mode in 'Memory', 'File') {
        $pr = $doc.CreateElement('Profile')
        $pr.SetAttribute('Id', "$name.Verbose.$mode"); $pr.SetAttribute('Name', $name)
        $pr.SetAttribute('Description', "PerfSnap: $($sets[$name] -join ' + ')"); $pr.SetAttribute('LoggingMode', $mode); $pr.SetAttribute('DetailLevel', 'Verbose')
        $col = $doc.CreateElement('Collectors')
        $sci = $doc.CreateElement('SystemCollectorId'); $sci.SetAttribute('Value', 'PerfSnap_System')
        $spi = $doc.CreateElement('SystemProviderId'); $spi.SetAttribute('Value', $spId); [void]$sci.AppendChild($spi)
        $eci = $doc.CreateElement('EventCollectorId'); $eci.SetAttribute('Value', 'PerfSnap_Event')
        $eps = $doc.CreateElement('EventProviders')
        foreach ($id in $epIds) { $e = $doc.CreateElement('EventProviderId'); $e.SetAttribute('Value', $id); [void]$eps.AppendChild($e) }
        [void]$eci.AppendChild($eps); [void]$col.AppendChild($sci); [void]$col.AppendChild($eci); [void]$pr.AppendChild($col)
        $tmp = $exported['CPU'].WindowsPerformanceRecorder.Profiles.Profile.TraceMergeProperties
        [void]$pr.AppendChild($doc.ImportNode($tmp, $true))
        $profileEls.Add($pr)
    }
    Write-Host ("{0}: {1} keywords, {2} stacks, {3} event providers" -f $name, $keywords.Count, $stacks.Count, $epIds.Count)
}

# The WPRP schema requires this order: collectors, system providers, event providers, profiles
foreach ($el in @($sysProviders) + @($evtProviders) + @($profileEls)) { [void]$profilesEl.AppendChild($el) }

$settings = New-Object Xml.XmlWriterSettings; $settings.Indent = $true; $settings.Encoding = New-Object Text.UTF8Encoding($false)
New-Item -ItemType Directory -Force -Path (Split-Path $Out) | Out-Null
$w = [Xml.XmlWriter]::Create($Out, $settings); $doc.Save($w); $w.Close()
Write-Host "Wrote $Out"
